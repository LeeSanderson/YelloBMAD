namespace Yello.Application.Spaces;

/// <summary>
/// Opens the one unit of work that creates a Space: the acting Account's own Membership count for the
/// Spaces-per-Account bound, and the new Space's rows, in one transaction. Story 3.1, open question 1 (a); AD-24
/// as amended on 2026-10-29, AD-25 / AR-30, AD-2.
/// </summary>
/// <remarks>
/// <para>
/// <b>The only unit of work that carries both session-context keys.</b> <c>AccountId</c> from the Session, so the
/// count can read the caller's Memberships across Spaces; <c>SpaceId</c> set to the new Space's server-generated
/// id, so the <c>BLOCK AFTER INSERT</c> predicates on <c>Membership</c> and <c>StatusDefinition</c> admit the new
/// Space's rows and no other Space's. AD-25 wants the count and the insert inside the same transaction; two units
/// of work would let two creations at 49 both pass. The AD-24 amendment names this exception and
/// <c>SpaceSwitcherGateTests.Exactly_one_creation_unit_of_work_sets_both_session_context_keys</c> holds it to one
/// type.
/// </para>
/// <para>
/// <b>It reads nothing but the count, and returns nothing but the new Space's identity.</b> The request pipeline
/// in <c>Yello.Host</c> is its only caller (AR-3): a slice never opens it.
/// </para>
/// </remarks>
public interface ISpaceCreationScope
{
    /// <summary>
    /// Opens the creation's unit of work, scoped to the acting Account and the new Space.
    /// </summary>
    /// <param name="accountId">The acting Account, from the Session (never from the request).</param>
    /// <param name="spaceId">The new Space's id, generated by the server (never from the request).</param>
    /// <param name="cancellationToken">The request's cancellation token.</param>
    /// <returns>The open unit of work.</returns>
    Task<ISpaceCreationUnitOfWork> BeginAsync(Guid accountId, Guid spaceId, CancellationToken cancellationToken);
}

/// <summary>
/// One Space creation's unit of work, which owns its connection from open to close. Disposing it without
/// <see cref="CompleteAsync"/> rolls everything back.
/// </summary>
public interface ISpaceCreationUnitOfWork : IAsyncDisposable
{
    /// <summary>
    /// The Account creating, and the id the new Space will have.
    /// </summary>
    SpaceCreationContext Context { get; }

    /// <summary>
    /// Commits the unit of work.
    /// </summary>
    /// <param name="cancellationToken">
    /// Cancels the commit; the pipeline passes <see cref="CancellationToken.None"/>, as it does for a Space-scoped
    /// unit of work.
    /// </param>
    /// <returns>A task that completes once the work is durable.</returns>
    Task CompleteAsync(CancellationToken cancellationToken);
}

/// <summary>
/// What a Space creation runs under: the Account the Session identifies, and the id the server generated for the
/// Space it is creating. Built by the request pipeline, never by a slice and never from the request (AD-2).
/// </summary>
/// <param name="AccountId">The acting Account.</param>
/// <param name="SpaceId">The new Space's id.</param>
public sealed record SpaceCreationContext(Guid AccountId, Guid SpaceId);
