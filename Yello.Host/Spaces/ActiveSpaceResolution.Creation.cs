using Yello.Application.Spaces;
using Yello.Domain;

namespace Yello.Host.Spaces;

/// <summary>
/// The Space creation step of the request pipeline: the one Account-scoped unit of work that writes. Story 3.1,
/// open questions 1 (a) and 2 (a), decided by Lee 2026-10-29; AD-24 as amended on 2026-10-29, AD-25 / AR-30,
/// AD-18 / AR-25, AD-2.
/// </summary>
/// <remarks>
/// <para>
/// <b>Part of <see cref="ActiveSpaceResolution"/>, deliberately</b>, beside <see cref="AccountScopedResolution"/>:
/// AR-3 makes the transaction, the keys, the bound and idempotency the pipeline's, and every A-12 gate holds that
/// only the pipeline reads the bound registry, the bound-count port and the idempotency ports. The slice
/// (<c>CreateSpaceHandler</c>) only provisions.
/// </para>
/// <para>
/// <b>Opted into by the endpoint's surface</b>, <see cref="AccountScopedSurface.SpaceCreation"/>, which
/// <see cref="AccountScopedResolution.EstablishAsync"/> has already turned into an <c>AccountScopedContext</c> - or
/// a <c>401</c> without a Session, before anti-forgery, recording nothing. A Token is no credential here: its
/// scheme authenticates nothing on a route without <c>{spaceId}</c>.
/// </para>
/// <para>
/// <b>In order:</b> the new Space's id is generated by the server (never the body's); the creation unit of work
/// opens under both session keys and both scopes; an <c>Idempotency-Key</c> already answered is replayed - before
/// the bound, so replaying the creation that reached 50 answers its <c>201</c>; the Spaces-per-Account bound is
/// counted under the Account's lock and a <c>409 bound-reached</c> returned at 50; the endpoint runs; a
/// materialised success is recorded for its key and committed, and anything else rolls back. A bound refusal
/// records no <c>AccessRefusal</c>: it is neither of AD-20's kinds.
/// </para>
/// </remarks>
internal static partial class ActiveSpaceResolution
{
    /// <summary>
    /// Runs a Space creation on its own unit of work, and passes every other request straight through. Registered
    /// once on the route group, after Space resolution.
    /// </summary>
    /// <param name="context">The request.</param>
    /// <param name="next">The rest of the pipeline.</param>
    /// <returns>The refusal, the replay, or whatever the endpoint returns.</returns>
    internal static ValueTask<object?> CreateSpaceAsync(
        EndpointFilterInvocationContext context,
        EndpointFilterDelegate next)
    {
        ArgumentNullException.ThrowIfNull(context);

        return context.HttpContext.GetEndpoint()?.Metadata.GetMetadata<AccountScopedEndpoint>()?.Surface
            == AccountScopedSurface.SpaceCreation
                ? SpaceCreation.CreateAsync(context, next)
                : next(context);
    }

    /// <summary>
    /// The creation step itself - nested, as <see cref="CreationBound"/> is, so it stays the pipeline's own for every
    /// gate while the resolution stays inside S1200's coupling limit.
    /// </summary>
    private static class SpaceCreation
    {
        internal static async ValueTask<object?> CreateAsync(EndpointFilterInvocationContext context, EndpointFilterDelegate next)
        {
            var httpContext = context.HttpContext;
            var services = httpContext.RequestServices;
            var cancellationToken = httpContext.RequestAborted;
            var logger = services.GetRequiredService<ILoggerFactory>().CreateLogger(LoggerCategory);

            // Established by AccountScopedResolution from the Session; absent only through a wiring defect, which
            // the holder reports by throwing rather than defaulting.
            var accountId = services.GetRequiredService<AccountScopedRequest>().Context.AccountId;
            var spaceId = services.GetRequiredService<IIdentifierGenerator>().Next();

            var unitOfWork = await services.GetRequiredService<ISpaceCreationScope>()
                .BeginAsync(accountId, spaceId, cancellationToken)
                .ConfigureAwait(false);

            await using (unitOfWork.ConfigureAwait(false))
            {
                services.GetRequiredService<SpaceCreationRequest>().Establish(unitOfWork.Context);

                var idempotent = await BeginAsync(httpContext, logger, accountId, cancellationToken).ConfigureAwait(false);

                var replayedOrRefused = idempotent.Answer
                    ?? await CreationBound.ConsultAsync(httpContext, logger, spaceId: null, cancellationToken).ConfigureAwait(false);

                var result = replayedOrRefused
                    ?? await RunAsync(context, next, logger, accountId, idempotent).ConfigureAwait(false);

                if (UnitOfWorkResults.IsFailure(result))
                {
                    return result;
                }

                await unitOfWork.CompleteAsync(CancellationToken.None).ConfigureAwait(false);

                // Only once committed, and only when this request created it: a replay creates nothing, and a creation
                // rolled back (its key in flight, or a failed commit) never existed.
                if (replayedOrRefused is null)
                {
                    SpaceLog.SpaceCreated(logger, spaceId);
                }

                return result;
            }
        }

        private static async Task<object?> RunAsync(
            EndpointFilterInvocationContext context,
            EndpointFilterDelegate next,
            ILogger logger,
            Guid accountId,
            IdempotentRequest idempotent)
        {
            var result = await next(context).ConfigureAwait(false);

            UnitOfWorkResults.EnsureMaterialised(result);

            if (UnitOfWorkResults.IsFailure(result) || idempotent.Key is null)
            {
                return result;
            }

            var httpContext = context.HttpContext;
            var record = IdempotentResponses.Capture(httpContext, idempotent.Fingerprint!, result);

            var recorded = await httpContext.RequestServices.GetRequiredService<IAccountIdempotencyStore>()
                .TryRecordAsync(accountId, idempotent.Key, record, httpContext.RequestAborted)
                .ConfigureAwait(false);

            if (recorded)
            {
                return IdempotentResponses.FirstAnswer(httpContext, record, result);
            }

            SpaceLog.CreationIdempotencyKeyRefused(logger, "in flight");

            // A Location the endpoint set describes a Space that is about to be rolled back.
            httpContext.Response.Headers.Remove("Location");

            return BoundaryProblems.IdempotencyKeyInFlight();
        }

        /// <summary>
        /// Reads the request's key and answers it from the Account's record when it has one - the Space-scoped
        /// step's rules, against the Account-scoped store.
        /// </summary>
        private static async Task<IdempotentRequest> BeginAsync(
            HttpContext httpContext,
            ILogger logger,
            Guid accountId,
            CancellationToken cancellationToken)
        {
            if (!IdempotentResponses.TryReadKey(httpContext.Request, out var key))
            {
                SpaceLog.CreationIdempotencyKeyRefused(logger, "malformed");

                return IdempotentRequest.Answered(BoundaryProblems.InvalidIdempotencyKey());
            }

            if (key is null)
            {
                return IdempotentRequest.None;
            }

            var fingerprint = await IdempotentResponses.FingerprintAsync(httpContext.Request, cancellationToken).ConfigureAwait(false);

            var recorded = await httpContext.RequestServices.GetRequiredService<IAccountIdempotencyStore>()
                .FindAsync(accountId, key, cancellationToken)
                .ConfigureAwait(false);

            if (recorded is null)
            {
                return new IdempotentRequest(key, fingerprint, Answer: null);
            }

            if (!string.Equals(recorded.Fingerprint, fingerprint, StringComparison.Ordinal))
            {
                SpaceLog.CreationIdempotencyKeyRefused(logger, "reused");

                return IdempotentRequest.Answered(BoundaryProblems.IdempotencyKeyReused());
            }

            SpaceLog.CreationReplayed(logger);

            return IdempotentRequest.Answered(IdempotentResponses.Replay(httpContext, recorded));
        }
    }
}

/// <summary>
/// The Space creation context established for this request, held for the endpoint to read - the creation
/// step's twin of <see cref="AccountScopedRequest"/>, for the same reason: minimal APIs bind arguments before
/// the filters run.
/// </summary>
public sealed class SpaceCreationRequest
{
    private SpaceCreationContext? _context;

    /// <summary>
    /// The context the pipeline established: the Account, and the server-generated id of the Space being created.
    /// Throws on an endpoint the pipeline did not establish one for.
    /// </summary>
    public SpaceCreationContext Context =>
        _context ?? throw new InvalidOperationException(
            "No Space creation context has been established on this request. It exists only on the endpoint "
            + "marked as AD-24's Space creation surface, inside the creation unit of work.");

    /// <summary>
    /// Records the context. The pipeline's creation step is the only caller.
    /// </summary>
    /// <param name="context">The context.</param>
    internal void Establish(SpaceCreationContext context) => _context = context;
}
