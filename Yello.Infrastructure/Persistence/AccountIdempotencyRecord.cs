namespace Yello.Infrastructure.Persistence;

/// <summary>
/// One <c>Idempotency-Key</c>'s recorded response for a request made without a Space - Space creation. AD-18 /
/// AR-25; story 3.1, open question 2 (a).
/// </summary>
/// <remarks>
/// <para>
/// <b>Account-scoped, under its own policy</b> (<c>AccountIsolationPolicy</c>: FILTER and BLOCK AFTER INSERT on
/// <c>fn_AccountIsolationPredicate</c> over <c>SESSION_CONTEXT('AccountId')</c>), with a query filter on the
/// request's Account. A stored body holds a Space's identity, which only its creator may read back.
/// </para>
/// <para>
/// <b><see cref="IdempotencyRecord"/>'s twin</b>, with no <c>SpaceId</c>: the request it answers named no Space,
/// and the Space it created belongs in the body, not in a scoping column.
/// </para>
/// </remarks>
internal sealed class AccountIdempotencyRecord
{
    /// <summary>
    /// The row's identity, generated by the application.
    /// </summary>
    internal required Guid Id { get; init; }

    /// <summary>
    /// The Account that sent it, and the column the policy reads.
    /// </summary>
    internal required Guid AccountId { get; init; }

    /// <summary>
    /// The key, as sent.
    /// </summary>
    internal required string Key { get; init; }

    /// <summary>
    /// Method, path and body hash of the request it answered.
    /// </summary>
    internal required string Fingerprint { get; init; }

    /// <summary>
    /// The response's status.
    /// </summary>
    internal required int StatusCode { get; init; }

    /// <summary>
    /// The response's content type, when it had a body.
    /// </summary>
    internal string? ContentType { get; init; }

    /// <summary>
    /// The response's <c>Location</c>, when it had one.
    /// </summary>
    internal string? Location { get; init; }

    /// <summary>
    /// The response's body.
    /// </summary>
    internal required string Body { get; init; }

    /// <summary>
    /// When it was recorded, in UTC. The record answers a retry for 24 hours from here.
    /// </summary>
    internal required DateTimeOffset CreatedAt { get; init; }
}
