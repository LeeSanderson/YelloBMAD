namespace Yello.Infrastructure.Persistence;

/// <summary>
/// One <c>Idempotency-Key</c>'s recorded response. AD-18 / AR-25; story 2.1, Task 7.
/// </summary>
/// <remarks>
/// <para>
/// <b>Space-scoped, under the Space policy</b> (FILTER and BLOCK AFTER INSERT), with a query filter like
/// every Space-scoped entity: a stored body holds Space content, a Project's name among it.
/// </para>
/// <para>
/// <b>Never a usable Token.</b> A response that carries a secret - an issued Token's plaintext - is
/// recorded with that property removed (NFR-6).
/// </para>
/// <para>
/// <b>Not a domain entity.</b> Idempotency is the request pipeline's, not the product's; the type lives
/// beside its adapter, as <see cref="DataProtectionKey"/> does.
/// </para>
/// </remarks>
internal sealed class IdempotencyRecord
{
    /// <summary>
    /// The row's identity, generated by the application.
    /// </summary>
    internal required Guid Id { get; init; }

    /// <summary>
    /// The Space the request acted in.
    /// </summary>
    internal required Guid SpaceId { get; init; }

    /// <summary>
    /// The Account that sent it.
    /// </summary>
    internal required Guid AccountId { get; init; }

    /// <summary>
    /// The key, as sent.
    /// </summary>
    internal required string Key { get; init; }

    /// <summary>
    /// Method, path and body hash of the request it answered.
    /// </summary>
    internal required string Fingerprint { get; init; }

    /// <summary>
    /// The response's status.
    /// </summary>
    internal required int StatusCode { get; init; }

    /// <summary>
    /// The response's content type, when it had a body.
    /// </summary>
    internal string? ContentType { get; init; }

    /// <summary>
    /// The response's <c>Location</c>, when it had one.
    /// </summary>
    internal string? Location { get; init; }

    /// <summary>
    /// The response's body, with any secret removed.
    /// </summary>
    internal required string Body { get; init; }

    /// <summary>
    /// When it was recorded, in UTC. The record answers a retry for 24 hours from here.
    /// </summary>
    internal required DateTimeOffset CreatedAt { get; init; }
}
