using Microsoft.EntityFrameworkCore.Storage;
using Yello.Application.Spaces;

namespace Yello.Infrastructure.Persistence;

/// <summary>
/// The Space creation unit of work: one transaction under both session-context keys - the acting Account's and
/// the new Space's - so the Spaces-per-Account count and the new Space's inserts commit together or not at all.
/// Story 3.1, open question 1 (a); AD-24 as amended on 2026-10-29, AD-25, AD-2.
/// </summary>
/// <remarks>
/// <para>
/// <b>The one type that sets both keys, and the AD-24 amendment's whole exception.</b> Every other unit of work
/// sets exactly one: <see cref="MembershipActiveSpaceResolver"/> the <c>SpaceId</c> key, the switcher's
/// <see cref="AccountSpaceDirectory"/> the <c>AccountId</c> key. A connection carrying both shows
/// <c>Membership</c>'s filter the caller's Memberships across Spaces, which is why the exception is held to this
/// type by <c>SpaceSwitcherGateTests.Exactly_one_creation_unit_of_work_sets_both_session_context_keys</c> - and why
/// what runs under it is held to the count, the inserts and the Account-scoped idempotency record.
/// </para>
/// <para>
/// <b>Why the inserts are admitted.</b> The <c>SpaceId</c> key names the new Space, generated by the server before
/// anything is written (AD-2), exactly as registration does; the <c>BLOCK AFTER INSERT</c> predicates on
/// <c>Membership</c> and <c>StatusDefinition</c> then admit rows of that Space and no other. <c>Membership</c>'s
/// BLOCK predicate stays Space-only (open question 1 (d) is forbidden), so the <c>AccountId</c> key lets nothing
/// be written into another Space.
/// </para>
/// <para>
/// <b>Both application-state scopes are narrowed to match</b> - <see cref="AccountScope"/> to the Account and
/// <see cref="SpaceScope"/> to the new Space, never <c>Resolve</c>d: no Role is held in a Space that does not
/// exist yet, so no <c>ActiveSpaceContext</c> exists on this request. Both return to the fail-closed state when
/// the unit of work ends.
/// </para>
/// </remarks>
/// <param name="dbContext">The request's unit of work.</param>
/// <param name="accountScope">The request's Account scope.</param>
/// <param name="spaceScope">The request's Space scope.</param>
internal sealed class SpaceCreationScope(YelloDbContext dbContext, AccountScope accountScope, SpaceScope spaceScope)
    : ISpaceCreationScope
{
    /// <inheritdoc />
    public async Task<ISpaceCreationUnitOfWork> BeginAsync(Guid accountId, Guid spaceId, CancellationToken cancellationToken)
    {
        var transaction = await dbContext.Database.BeginTransactionAsync(cancellationToken).ConfigureAwait(false);

        try
        {
            await SpaceSessionContext.SetAccountAsync(dbContext.Database, accountId, cancellationToken).ConfigureAwait(false);
            await SpaceSessionContext.SetAsync(dbContext.Database, spaceId, cancellationToken).ConfigureAwait(false);

            accountScope.Narrow(accountId);
            spaceScope.Narrow(spaceId);

            return new UnitOfWork(transaction, new SpaceCreationContext(accountId, spaceId), accountScope, spaceScope);
        }
        catch
        {
            accountScope.Clear();
            spaceScope.Clear();
            await transaction.DisposeAsync().ConfigureAwait(false);
            throw;
        }
    }

    /// <summary>
    /// The open transaction and the context it runs under.
    /// </summary>
    private sealed class UnitOfWork(
        IDbContextTransaction transaction,
        SpaceCreationContext context,
        AccountScope accountScope,
        SpaceScope spaceScope)
        : ISpaceCreationUnitOfWork
    {
        /// <inheritdoc />
        public SpaceCreationContext Context => context;

        /// <inheritdoc />
        public Task CompleteAsync(CancellationToken cancellationToken) => transaction.CommitAsync(cancellationToken);

        /// <inheritdoc />
        public ValueTask DisposeAsync()
        {
            accountScope.Clear();
            spaceScope.Clear();

            return transaction.DisposeAsync();
        }
    }
}
